"""Build docs/RESULTS.md tables from an evidence folder results/<run_id>.
See docs/TESTING.md#evidence.

    python scripts/build_results.py results/<run_id>

Reads results/<run_id>/sessions/*.json (one per pytest invocation: every
test's status) and results/<run_id>/<test_id>/summary.json (key numbers of
each world test). Nothing is typed in by hand: a missing input shows as
NOT RUN, never as a guessed number.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "RESULTS.md"
NOT_RUN = "NOT RUN"
SCHEMA = "dialog-state/0.1-experimental"


def recovery_ms_from_events(events: list[dict[str, Any]]) -> float | None:
    """From the failing owner's last write to the first resumed/reclaimed event.

    Events written in the same transaction as the resume (same timestamp, for
    example its state_changed) are not "before" it and are skipped.
    """
    for i, e in enumerate(events):
        if e["type"] not in ("resumed", "reclaimed"):
            continue
        owner = e["data"].get("previous_owner") or e["actor"]
        before = [
            x
            for x in events[:i]
            if x["task_id"] == e["task_id"] and x["actor"] == owner and x["ts"] < e["ts"]
        ]
        if not before:
            return None
        delta = datetime.fromisoformat(e["ts"]) - datetime.fromisoformat(before[-1]["ts"])
        return round(delta.total_seconds() * 1000, 1)
    return None


class Run:
    def __init__(self, folder: Path) -> None:
        self.folder = folder
        self.run_id = folder.name
        self.sessions = [
            json.loads(p.read_text()) for p in sorted((folder / "sessions").glob("*.json"))
        ]
        self.tests: list[dict[str, Any]] = [t for s in self.sessions for t in s["tests"]]
        self.summaries: dict[str, dict[str, Any]] = {}
        for p in sorted(folder.glob("*/summary.json")):
            data = json.loads(p.read_text())
            self.summaries[data["test_id"]] = data

    # --- lookups --------------------------------------------------------------------

    def meta(self, key: str) -> str:
        values = [s.get(key) for s in self.sessions if s.get(key)]
        return str(values[-1]) if values else "unknown"

    def summary(self, test_id: str) -> dict[str, Any] | None:
        return self.summaries.get(test_id)

    def numbers(self, test_id: str) -> dict[str, Any]:
        s = self.summary(test_id)
        return s["numbers"] if s else {}

    def events(self, test_id: str) -> list[dict[str, Any]]:
        path = self.folder / test_id / "events.json"
        return json.loads(path.read_text()) if path.exists() else []

    def status(self, test_id: str) -> str:
        s = self.summary(test_id)
        if s:
            return s["status"]
        found = [t["status"] for t in self.tests if t["test_id"] == test_id]
        return found[-1] if found else NOT_RUN

    def group_status(self, match) -> tuple[str, int, int]:
        """PASS only if every matching test passed; otherwise the worst status seen."""
        rows = [t for t in self.tests if match(t)]
        if not rows:
            return NOT_RUN, 0, 0
        passed = sum(t["status"] == "PASS" for t in rows)
        worst = next(
            (s for s in ("TIMEOUT", "FAIL", "ERROR") if any(t["status"] == s for t in rows)), "PASS"
        )
        return worst, passed, len(rows)

    def stability(self) -> tuple[int, int, int] | None:
        repeats = [
            t
            for t in self.tests
            if ("official" in t["markers"] or "extra" in t["markers"]) and "-" in t["test_id"]
        ]
        if not repeats:
            return None
        count = max(int(t["test_id"].rsplit("-", 1)[1]) for t in repeats)
        return sum(t["status"] == "PASS" for t in repeats), len(repeats), count


def fmt_dups(value: Any) -> str:
    if isinstance(value, dict):
        return ", ".join(f"{k}: {v}" for k, v in value.items())
    return "—" if value is None else str(value)


def fmt_ms(value: Any) -> str:
    return "—" if value in (None, "") else f"{value:.0f} ms"


def yes(value: Any) -> str:
    return {True: "yes", False: "**no**"}.get(value, "—")


def evidence(run: Run, test_id: str) -> str:
    return f"`results/{run.run_id}/{test_id}`" if run.summary(test_id) else "—"


# --- the document ---------------------------------------------------------------------


def render(run: Run) -> str:
    out: list[str] = []
    w = out.append
    c1 = run.numbers("c1")
    w("# Results\n")
    w(
        "> This file is generated by `scripts/build_results.py` from real runs in\n"
        "> `results/<run_id>/`. **Do not type numbers in by hand.** Every number below\n"
        "> traces back to an evidence folder (kept locally and as a CI artifact; the\n"
        "> `results/` folder itself is not committed).\n"
    )
    w(f"- Run ID: `{run.run_id}`")
    w(f"- Git commit: `{run.meta('git_commit')}`")
    w(f"- Python: `{run.meta('python')}` · OS: `{run.meta('os')}`")
    w(f"- Mode: {run.meta('test_mode')} · Seed: `{c1.get('seed', NOT_RUN)}`")
    w(f"- Schema: `{SCHEMA}`\n")

    w("## 1. The five PS-021 disconnect/retry scenarios\n")
    w(
        "| ID | Scenario | Status | Task ID preserved | Side effects (expected 1) "
        "| Duplicates rejected | Recovery time | Evidence |"
    )
    w("| --- | --- | --- | --- | --- | --- | --- | --- |")
    names = {
        "s1": "Lost reply, sender retries",
        "s2": "Two workers race",
        "s3": "Crash before side effect",
        "s4": "Crash after side effect, before report",
        "s5": "Bridge hard kill during network cut",
    }
    for tid, name in names.items():
        n = dict(run.numbers(tid))
        if tid in ("s3", "s4"):  # measured from the saved event log, not a recorded number
            n["recovery_ms"] = recovery_ms_from_events(run.events(tid))
        w(
            f"| {tid.upper()} | {name} | {run.status(tid)} | {yes(n.get('task_id_preserved'))} "
            f"| {n.get('side_effects', '—')} | {fmt_dups(n.get('duplicates_rejected'))} "
            f"| {fmt_ms(n.get('recovery_ms'))} | {evidence(run, tid)} |"
        )
    w(
        "\nRecovery time: from the failing worker's last write to the `resumed` event (S3, S4,"
        " includes the process restart); for S5, from the last event before the kill to"
        " `bridge_started`.\n"
    )

    w("## 2. Baseline\n")
    w("| ID | Status | Avg task duration | Events per task |")
    w("| --- | --- | --- | --- |")
    s0 = run.numbers("s0")
    w(
        f"| S0 | {run.status('s0')} | {fmt_ms(s0.get('avg_task_ms'))} "
        f"| {s0.get('events_per_task', '—')} |\n"
    )

    w("## 3. Interoperability\n")
    w("| ID | Check | Status | Notes |")
    w("| --- | --- | --- | --- |")
    i1 = run.group_status(lambda t: "test_codecs.py" in t["nodeid"] and "mcp_style" in t["nodeid"])
    i2 = run.group_status(
        lambda t: (
            "test_codecs.py" in t["nodeid"]
            and ("a2a_style" in t["nodeid"] or "suspended" in t["nodeid"].lower())
        )
    )
    w(f"| I1 | MCP-style round trip, all ops | {i1[0]} | {i1[1]}/{i1[2]} codec checks |")
    w(
        f"| I2 | A2A-style round trip, all states | {i2[0]} | {i2[1]}/{i2[2]} codec checks;"
        " SUSPENDED carried in `metadata.bridge_state` |"
    )
    w(
        f"| I3 | Same dialog/task IDs across both views | {run.status('i3')} | {evidence(run, 'i3')} |\n"
    )
    w(
        "**Finding:** the A2A-style state set has no equivalent for SUSPENDED. The\n"
        "mapping is lossy by itself; the codec keeps it lossless through an extension\n"
        "field.\n"
    )

    w("## 4. Additional scenarios\n")
    w("| ID | Scenario | Status | Key number |")
    w("| --- | --- | --- | --- |")
    extras = {
        "x1": "Uncertain side-effect outcome",
        "x2": "Slow, not dead, worker",
        "x3": "Orchestrator crash after create",
        "x4": "Retry limit",
        "x5": "Cancel before side effect",
        "x6": "Dependency failure",
        "x7": "Duplicate dispatch",
    }
    for tid, name in extras.items():
        w(
            f"| {tid.upper()} | {name} | {run.status(tid)} | {run.numbers(tid).get('key_number', '—')} |"
        )
    w("")

    w("## 5. Rules enforced\n")
    w("| ID | Attempt | Expected | Status |")
    w("| --- | --- | --- | --- |")
    rules = {
        "r1": ("Invalid transition", "409"),
        "r2": ("Unknown schema version", "400"),
        "r3": ("Stale fence", "409"),
        "r4": ("Reused request ID", "422"),
    }
    for tid, (attempt, code) in rules.items():
        st = run.group_status(lambda t, tid=tid: t["test_id"] == tid)
        w(f"| {tid.upper()} | {attempt} | {code} | {st[0]} |")
    unit = run.group_status(
        lambda t: "/unit/" in t["nodeid"] or t["nodeid"].startswith("tests/unit")
    )
    w(
        f"\nUnit tests (router, state machine, codecs, models, faults): {unit[0]}, {unit[1]}/{unit[2]}.\n"
    )

    w("## 6. Protection on vs off (mutation check M1)\n")
    w("| Scenario | Protection ON | Protection OFF |")
    w("| --- | --- | --- |")
    s1, s4 = run.numbers("s1"), run.numbers("s4")
    m1s1, m1s4 = run.numbers("m1_s1"), run.numbers("m1_s4")
    on1 = f"{s1['dialogs_for_msg']} dialog, {s1['side_effects']} payment" if s1 else NOT_RUN
    off1 = (
        f"{m1s1['dialogs_for_msg']} dialogs for one message ({run.status('m1_s1')})"
        if m1s1
        else NOT_RUN
    )
    on4 = f"{s4['side_effects']} payment" if s4 else NOT_RUN
    off4 = f"{m1s4['side_effects']} payments ({run.status('m1_s4')})" if m1s4 else NOT_RUN
    w(f"| S1 | {on1} | {off1} |")
    w(f"| S4 | {on4} | {off4} |\n")
    w(
        "M1 passes when the duplicates appear with protection off: it proves S1 and S4 would catch broken dedup.\n"
    )

    w("## 7. Chaos run (C1)\n")
    w(
        "| Tasks | Faults applied | Crashes | Duplicate requests absorbed "
        "| Duplicate effects rejected | **Duplicate side effects** | Stuck tasks |"
    )
    w("| --- | --- | --- | --- | --- | --- | --- |")
    if c1:
        w(
            f"| {c1['tasks']} ({c1['messages']} messages) | {c1['bridge_faults_applied']} on the bridge"
            f" ({c1['fault_rules_set']} rules set) | {c1['crashes']} "
            f"| {c1['duplicate_requests_absorbed']} | {c1['duplicate_effects_rejected']} "
            f"| **{c1['duplicate_side_effects']}** | {c1['stuck_tasks']} |"
        )
        w(
            f"\nStatus: {run.status('c1')}. Outcomes: {c1['completed']} completed, {c1['failed']} failed"
            f" (retry limit), {c1['cancelled']} cancelled. Actions-service faults are counted as"
            " rules set, since that service logs them instead of writing events.\n"
        )
    else:
        w(f"| {NOT_RUN} | | | | | | |\n")

    w("## 8. Stability\n")
    stab = run.stability()
    if stab:
        passed, total, count = stab
        w(f'`pytest -m "official or extra" --count={count}`: {passed}/{total}.\n')
    else:
        w(f'`pytest -m "official or extra" --count=20`: {NOT_RUN} in this run.\n')

    w("## 9. What these results do and do not show\n")
    w(
        "They show that, within this prototype's assumptions\n"
        "([DEDUP_AND_RECOVERY.md](DEDUP_AND_RECOVERY.md#assumptions)), task identity\n"
        "was preserved and no side effect was performed twice in any tested scenario.\n"
        "They do not show delivery guarantees in general, full MCP or A2A\n"
        "interoperability, or conformance to any IETF document\n"
        "([LIMITATIONS.md](LIMITATIONS.md))."
    )
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    folder = Path(argv[1])
    if not folder.is_absolute():
        folder = (Path.cwd() / folder).resolve()
    if not (folder / "sessions").is_dir():
        print(f"{folder} has no sessions/ folder: run the tests with RUN_ID set first")
        return 1
    OUT.write_text(render(Run(folder)), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} from {folder}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
